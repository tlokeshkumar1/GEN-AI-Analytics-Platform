"""Versioned semantic and analytical definitions with server-enforced approvals."""

import copy
import os
import threading
import time
import uuid
from datetime import datetime, timezone

from fastapi import HTTPException

from api.models.execution_context import current_identity, require_dataset_access
from api.models.query_plan import QueryPlan
from api.platform.contracts import (
    AnalyticsItem,
    AnalyticsPlan,
    SemanticField,
    SemanticModel,
)
from api.platform.store import metadata_store
from api.utils.logger import get_logger

logger = get_logger("platform.semantic")

_RECOMMENDATION_CACHE: dict = {}
_RECOMMENDATION_CACHE_LOCK = threading.Lock()
_RECOMMENDATION_CACHE_TTL = 300.0  # 5 minutes


def now():
    return datetime.now(timezone.utc).isoformat()


class SemanticRegistry:
    def __init__(self, store=None):
        self._store = store
        self._cache_lock = threading.Lock()
        self._list_cache: dict[tuple, tuple[float, list]] = {}
        self._get_cache: dict[tuple, tuple[float, dict]] = {}
        self._items_cache: dict[tuple, tuple[float, list]] = {}
        self._cache_ttl = 60.0

    @property
    def store(self):
        return self._store or metadata_store()

    def _invalidate_cache(self):
        with self._cache_lock:
            self._list_cache.clear()
            self._get_cache.clear()
            self._items_cache.clear()

    def _clear_cache(self):
        self._invalidate_cache()

    def namespace(self, entry, version, category="semantic"):
        ws = entry.get("workspaceId") or "default"
        return f"{ws}:{category}:{entry['id']}:v{version}"

    def list(
        self, entry, version, for_chat: bool = False, allow_chat_member: bool = False
    ):
        require_dataset_access(entry, for_chat=for_chat or allow_chat_member)
        ns = self.namespace(entry, version)
        store = self.store
        cache_key = (
            id(store),
            str(getattr(store, "path", "")),
            getattr(store, "_write_seq", 0),
            ns,
        )
        now_ts = time.monotonic()
        with self._cache_lock:
            cached = self._list_cache.get(cache_key)
            if cached and (now_ts - cached[0]) < self._cache_ttl:
                return copy.deepcopy(cached[1])
        rows = [row["value"] for row in store.list(ns)]
        with self._cache_lock:
            if len(self._list_cache) >= 64:
                self._list_cache.clear()
            self._list_cache[cache_key] = (now_ts, copy.deepcopy(rows))
        return rows

    def get(
        self,
        entry,
        version,
        revision,
        approved=False,
        for_chat: bool = False,
        allow_chat_member: bool = False,
    ):
        require_dataset_access(entry, for_chat=for_chat or allow_chat_member)
        ns = self.namespace(entry, version)
        store = self.store
        cache_key = (
            id(store),
            str(getattr(store, "path", "")),
            getattr(store, "_write_seq", 0),
            ns,
            str(revision),
        )
        now_ts = time.monotonic()
        raw_value = None
        with self._cache_lock:
            cached = self._get_cache.get(cache_key)
            if cached and (now_ts - cached[0]) < self._cache_ttl:
                raw_value = cached[1]
        if raw_value is None:
            row = store.get(ns, str(revision))
            if row is None:
                raise HTTPException(
                    409,
                    "Review a semantic model for this dataset version before running analytics.",
                )
            raw_value = row["value"]
            with self._cache_lock:
                if len(self._get_cache) >= 128:
                    self._get_cache.clear()
                self._get_cache[cache_key] = (now_ts, raw_value)
        model = SemanticModel.model_validate(raw_value)
        if approved and model.status != "approved":
            if os.getenv("PLATFORM_AUTO_APPROVE_SEMANTICS", "true").lower() != "true":
                raise HTTPException(
                    409,
                    "Review and approve the semantic model before running analytics.",
                )
            # For dynamic self-service analytics, allow proposed models generated by Agent 2 to proceed
            logger.info(
                f"Using auto-profiled semantic model (status: {model.status}) for dataset {entry.get('id')}"
            )
        return model

    def propose(self, entry, version, snapshot, overrides=None):
        require_dataset_access(entry, write=True)
        existing = self.list(entry, version)
        revision = max([m["revision"] for m in existing] + [0]) + 1
        if overrides:
            model = SemanticModel.model_validate(
                {
                    **overrides,
                    "dataset_id": entry["id"],
                    "data_version": version,
                    "revision": revision,
                    "status": "proposed",
                    "reviewer": None,
                    "reviewed_at": None,
                }
            )
        else:
            fields = []
            for column in snapshot["columns"]:
                name, kind = column["name"], column["type"]
                kind = {"number": "decimal", "percentage": "decimal"}.get(kind, kind)
                identifier = kind == "identifier" or name.lower().endswith(
                    ("id", "code", "key")
                )
                numeric = kind in ("decimal", "integer") and not identifier
                restricted = column.get("unit") == "%" or any(
                    word in name.lower()
                    for word in (
                        "percent",
                        "ratio",
                        "rate",
                        "balance",
                        "inventory",
                        "stock",
                        "price",
                    )
                )
                aggregations = ["COUNT", "COUNT_DISTINCT"]
                if numeric:
                    aggregations += ["MIN", "MAX", "AVG"] + (
                        [] if restricted else ["SUM"]
                    )
                role = (
                    "identifier"
                    if identifier
                    else "time"
                    if kind == "date"
                    else "measure"
                    if numeric
                    else "dimension"
                )
                fields.append(
                    SemanticField(
                        name=name,
                        semantic_name=name,
                        type=kind,
                        role=role,
                        aggregations=aggregations,
                        unit=column.get("unit"),
                        currency=column.get("currency"),
                        default_aggregation=None,
                        evidence="Inferred from source values and field name; aggregation and business meaning require review.",
                    )
                )
            raw_name = str(entry.get("folder") or entry.get("name") or "").rsplit(
                ".", 1
            )[0]
            clean_domain = (
                " ".join(
                    part
                    for part in raw_name.replace("_", " ").replace("-", " ").split()
                    if part
                ).title()
                or "Open-Domain"
            )
            model = SemanticModel(
                dataset_id=entry["id"],
                data_version=version,
                revision=revision,
                domain=clean_domain,
                fields=fields,
            )
        physical = {c["name"] for c in snapshot["columns"]}
        names = [f.name for f in model.fields]
        if len(set(names)) != len(names) or set(names) != physical:
            raise HTTPException(
                422, "Semantic fields must match the dataset fields exactly."
            )
        from api.services.dataset_service import dataset_service
        from api.platform.formulas import formula, validated_join
        from decimal import Decimal

        frame = dataset_service._frame(snapshot["rows"], snapshot["columns"])
        relationship_ids = [relationship.id for relationship in model.relationships]
        if len(set(relationship_ids)) != len(relationship_ids):
            raise HTTPException(422, "Relationship identifiers must be unique.")
        for relationship in model.relationships:
            right = dataset_service._entry(
                dataset_service._catalog(), relationship.right_dataset_id
            )
            right_snapshot = dataset_service._snapshot(
                right, relationship.right_version
            )
            self.get(
                right,
                relationship.right_version,
                relationship.right_semantic_revision,
                approved=True,
            )
            right_frame = dataset_service._frame(
                right_snapshot["rows"], right_snapshot["columns"]
            )
            try:
                joined = validated_join(frame, right_frame, relationship, "inner")
            except (ValueError, TypeError, KeyError) as exc:
                raise HTTPException(422, str(exc)) from None
            left_count = len(frame.dropna(subset=relationship.left_keys))
            relationship.evidence = {
                "left_non_null_rows": left_count,
                "matched_left_rows": len(joined),
                "right_rows": len(right_frame),
                "right_key_unique": True,
            }
            if len(joined) == 0:
                raise HTTPException(
                    422, "Relationship has no matching keys between datasets."
                )
        fields = {field.name: field for field in model.fields}
        for metric in model.derived_metrics:
            if metric.name in fields:
                raise HTTPException(
                    422, "Derived metric names must differ from physical fields."
                )
            for dependency in metric.dependencies.values():
                field = fields.get(dependency.field)
                if field is None or dependency.aggregation not in field.aggregations:
                    raise HTTPException(
                        422,
                        "Derived metric dependency uses an unapproved field or aggregation.",
                    )
            try:
                formula(
                    metric.expression, {key: Decimal(1) for key in metric.dependencies}
                )
            except (ValueError, SyntaxError) as exc:
                raise HTTPException(422, str(exc)) from None
        self.store.put(
            self.namespace(entry, version), str(revision), model.model_dump(mode="json")
        )
        self.store.put(
            self.namespace(entry, version, "workflow"),
            f"semantic:{revision}",
            {
                "stage": "semantic_review",
                "status": "awaiting_review",
                "semantic_revision": revision,
                "created_at": now(),
            },
        )
        return model

    def review(self, entry, version, revision, decision):
        require_dataset_access(entry, write=True)
        namespace = self.namespace(entry, version)
        row = self.store.get(namespace, str(revision))
        if row is None:
            raise HTTPException(404, "Semantic revision not found.")
        model = SemanticModel.model_validate(row["value"])
        if model.status != "proposed":
            raise HTTPException(
                409,
                "Reviewed definitions are immutable. Create a new revision to edit.",
            )
        if decision == "approved" and (
            not model.grain.strip() or model.grain.startswith("Unconfirmed")
        ):
            if os.getenv("PLATFORM_AUTO_APPROVE_SEMANTICS", "true").lower() != "true":
                raise HTTPException(
                    409,
                    "Confirm what one source row represents before approving the semantic model.",
                )
            model.grain = (
                f"Single record of {model.domain}"
                if model.domain
                else "Single record entity"
            )
        identity = current_identity.get()
        reviewer_id = (
            identity["user_id"] if identity else (entry.get("createdBy") or "system")
        )
        model.status, model.reviewer, model.reviewed_at = decision, reviewer_id, now()
        self.store.put(
            namespace, str(revision), model.model_dump(mode="json"), row["revision"]
        )
        return model

    def items(
        self,
        entry,
        version,
        revision,
        allow_chat_member: bool = False,
        for_chat: bool = False,
    ):
        require_dataset_access(entry, for_chat=allow_chat_member or for_chat)
        ns = self.namespace(entry, version, f"analytics:{revision}")
        store = self.store
        cache_key = (
            id(store),
            str(getattr(store, "path", "")),
            getattr(store, "_write_seq", 0),
            ns,
        )
        now_ts = time.monotonic()
        with self._cache_lock:
            cached = self._items_cache.get(cache_key)
            if cached and (now_ts - cached[0]) < self._cache_ttl:
                return [
                    AnalyticsItem.model_validate(val)
                    for val in copy.deepcopy(cached[1])
                ]
        rows = [row["value"] for row in store.list(ns)]
        with self._cache_lock:
            if len(self._items_cache) >= 64:
                self._items_cache.clear()
            self._items_cache[cache_key] = (now_ts, copy.deepcopy(rows))
        return [AnalyticsItem.model_validate(val) for val in rows]

    def persist_recommendations(
        self,
        entry,
        version,
        revision,
        recommendations,
        model=None,
        require_review=False,
    ):
        """Persist unique recommendations; user-facing generation can require explicit review."""
        from api.platform.agent_chart_recommender import (
            concept_signature,
            extract_query_dependencies,
            recommendation_signature,
        )

        if model is None:
            model = self.get(entry, version, revision, approved=True)

        existing = self.items(entry, version, revision)
        existing_ids = {item.id for item in existing}
        seen_sigs = {recommendation_signature(item) for item in existing}
        seen_concepts = {concept_signature(item) for item in existing}
        namespace = self.namespace(entry, version, f"analytics:{revision}")

        saved: list[AnalyticsItem] = []
        auto_approve = (
            not require_review
            and os.getenv("PLATFORM_AUTO_APPROVE_SEMANTICS", "true").lower() == "true"
        )
        for rec in recommendations:
            query = QueryPlan.model_validate(rec["query_plan"])
            sig = recommendation_signature({"kind": rec["kind"], "query_plan": query})
            concept = concept_signature({"kind": rec["kind"], "query_plan": query})
            if sig in seen_sigs or concept in seen_concepts:
                continue
            item_id = str(rec.get("id") or uuid.uuid4().hex)
            if item_id in existing_ids:
                item_id = f"{item_id}_{uuid.uuid4().hex[:6]}"
            item = AnalyticsItem(
                id=item_id,
                title=rec["title"],
                kind=rec["kind"],
                revision=1,
                semantic_revision=revision,
                query_plan=query,
                dependencies=extract_query_dependencies(model, query),
                explanation=rec.get("explanation")
                or f"Recommended {rec['kind']} view for {rec['title']}.",
                status="approved" if auto_approve else "proposed",
                reviewer="system" if auto_approve else None,
                reviewed_at=now() if auto_approve else None,
            )
            self.store.put(namespace, f"{item.id}:1", item.model_dump(mode="json"))
            saved.append(item)
            existing_ids.add(item.id)
            seen_sigs.add(sig)
            seen_concepts.add(concept)
        return saved

    def propose_analytics(self, entry, version, revision, snapshot, fast_only=False):
        require_dataset_access(entry)
        model = self.get(entry, version, revision, approved=True)

        # --- recommendation cache ---
        cache_key = (entry["id"], version, revision, fast_only)
        now_ts = time.monotonic()
        with _RECOMMENDATION_CACHE_LOCK:
            cached = _RECOMMENDATION_CACHE.get(cache_key)
            if (
                cached
                and fast_only
                and (now_ts - cached[0]) < _RECOMMENDATION_CACHE_TTL
            ):
                return cached[1]

        from api.platform.agent_chart_recommender import chart_recommender_agent
        from api.services.dataset_service import dataset_service

        existing = self.items(entry, version, revision)
        df = dataset_service._frame(snapshot["rows"], snapshot["columns"])
        dataset_name = (
            entry.get("displayName") or entry.get("name") or entry.get("folder")
        )
        recommendations = chart_recommender_agent.recommend(
            df,
            model,
            existing_items=existing,
            dataset_name=dataset_name,
            fast_only=fast_only,
        )
        items = self.persist_recommendations(
            entry, version, revision, recommendations, model=model, require_review=True
        )
        result = AnalyticsPlan(
            dataset_id=entry["id"],
            data_version=version,
            semantic_revision=revision,
            items=items,
        )

        with _RECOMMENDATION_CACHE_LOCK:
            if len(_RECOMMENDATION_CACHE) >= 128:
                _RECOMMENDATION_CACHE.clear()
            _RECOMMENDATION_CACHE[cache_key] = (time.monotonic(), result)

        return result

    def save_item(self, entry, version, semantic_revision, proposed):
        require_dataset_access(entry)
        model = self.get(entry, version, semantic_revision, approved=True)
        from api.platform.agent_chart_recommender import extract_query_dependencies

        previous = [
            i
            for i in self.items(entry, version, semantic_revision)
            if i.id == proposed["id"]
        ]
        revision = max([i.revision for i in previous] + [0]) + 1
        item = AnalyticsItem.model_validate(
            {
                **proposed,
                "revision": revision,
                "semantic_revision": semantic_revision,
                "status": "proposed",
                "reviewer": None,
                "reviewed_at": None,
            }
        )
        item.dependencies = extract_query_dependencies(model, item.query_plan)
        self.store.put(
            self.namespace(entry, version, f"analytics:{semantic_revision}"),
            f"{item.id}:{revision}",
            item.model_dump(mode="json"),
        )
        return item

    def review_item(
        self, entry, version, semantic_revision, item_id, revision, decision
    ):
        require_dataset_access(entry, write=True)
        self.get(entry, version, semantic_revision, approved=True)
        namespace = self.namespace(entry, version, f"analytics:{semantic_revision}")
        key = f"{item_id}:{revision}"
        row = self.store.get(namespace, key)
        if row is None:
            raise HTTPException(404, "Analytics definition not found.")
        item = AnalyticsItem.model_validate(row["value"])
        confirming = (
            item.status == "approved"
            and item.reviewer == "system"
            and decision == "approved"
        )
        if item.status != "proposed" and not confirming:
            raise HTTPException(
                409, "Create a new definition revision to change a reviewed item."
            )
        identity = current_identity.get()
        if identity is None:
            raise HTTPException(401, "A verified reviewer is required.")
        item.status, item.reviewer, item.reviewed_at = (
            decision,
            identity["user_id"],
            now(),
        )
        self.store.put(namespace, key, item.model_dump(mode="json"), row["revision"])
        return item

    def delete_items(self, entry, version, semantic_revision, targets) -> int:
        """Delete one or more analytics definitions and prune any stale references from the published dashboard."""
        require_dataset_access(entry, write=True)
        if not targets:
            return 0
        with self.store.transaction():
            analytics_ns = self.namespace(
                entry, version, f"analytics:{semantic_revision}"
            )
            deleted_count = 0
            for item_id, revision in targets:
                deleted_count += self.store.delete(
                    analytics_ns, f"{item_id}:{revision}"
                )
            if deleted_count > 0:
                dashboard_ns = self.namespace(
                    entry, version, f"dashboard:{semantic_revision}"
                )
                existing_pub = self.store.get(dashboard_ns, "published")
                if existing_pub and isinstance(
                    existing_pub["value"].get("items"), list
                ):
                    target_set = {(str(item_id), int(rev)) for item_id, rev in targets}
                    filtered_items = [
                        ref
                        for ref in existing_pub["value"]["items"]
                        if (str(ref.get("id")), int(ref.get("revision", 1)))
                        not in target_set
                    ]
                    if len(filtered_items) != len(existing_pub["value"]["items"]):
                        updated_pub = {**existing_pub["value"], "items": filtered_items}
                        self.store.put(
                            dashboard_ns,
                            "published",
                            updated_pub,
                            expected_revision=existing_pub["revision"],
                        )
            return deleted_count

    def reuse(
        self,
        entry,
        source_version,
        target_version,
        revision,
        source_snapshot,
        target_snapshot,
    ):
        with self.store.transaction():
            return self._reuse(
                entry,
                source_version,
                target_version,
                revision,
                source_snapshot,
                target_snapshot,
            )

    def _reuse(
        self,
        entry,
        source_version,
        target_version,
        revision,
        source_snapshot,
        target_snapshot,
    ):
        require_dataset_access(entry, write=True)
        if source_snapshot["columns"] != target_snapshot[
            "columns"
        ] or source_snapshot.get("transformationPlan") != target_snapshot.get(
            "transformationPlan"
        ):
            raise HTTPException(
                409,
                "Schema, units or transformations changed. Review a new semantic model before reusing definitions.",
            )
        if self.list(entry, target_version):
            raise HTTPException(
                409,
                "The target version already has semantic revisions. Review those definitions explicitly.",
            )
        model = self.get(entry, source_version, revision, approved=True)
        proposed = self.propose(
            entry, target_version, target_snapshot, model.model_dump(mode="json")
        )
        approved = self.review(entry, target_version, proposed.revision, "approved")
        items = self.items(entry, source_version, revision)
        approved_items = [item for item in items if item.status == "approved"]
        target_namespace = self.namespace(
            entry, target_version, f"analytics:{approved.revision}"
        )
        for item in approved_items:
            clone = item.model_copy(update={"semantic_revision": approved.revision})
            self.store.put(
                target_namespace,
                f"{item.id}:{item.revision}",
                clone.model_dump(mode="json"),
            )
        publication = self.store.get(
            self.namespace(entry, source_version, f"dashboard:{revision}"), "published"
        )
        if publication:
            self.store.put(
                self.namespace(entry, target_version, f"dashboard:{approved.revision}"),
                "published",
                publication["value"],
            )
        return {
            "model": approved.model_dump(mode="json"),
            "reused_definitions": len(approved_items),
            "source_version": source_version,
        }


semantic_registry = SemanticRegistry()
